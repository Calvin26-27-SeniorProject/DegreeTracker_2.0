// Every course any program page lists, for the Major and Minor pages' course
// rows (title, catalog hours, link) where no checked program file covers a
// program: built from the generated programs/<year>/**/program.json files.
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
export const PROGRAMS_DIR = join(ROOT, 'programs');
export const COURSE_INDEX_PATH = join(PROGRAMS_DIR, 'course-index.json');
const COURSE_URL_RE = /^https:\/\/catalog\.calvin\.edu\/preview_course_nopop\.php\?catoid=(\d+)&coid=(\d+)$/;

function programFiles(dir) {
  const found = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...programFiles(path));
    else if (entry.name === 'program.json') found.push(path);
  }
  return found.sort();
}

// { _meta, courses: { [code]: [title, credits, "catoid:coid" | null] } }, codes
// sorted. A course listed in several years takes the newest year's entry; within
// a year, the first program (by path) that lists it.
export function buildCourseIndex(dir = PROGRAMS_DIR) {
  const years = readdirSync(dir).filter(d => /^\d{4}$/.test(d)).sort().reverse();
  const courses = new Map();
  for (const year of years) {
    for (const path of programFiles(join(dir, year))) {
      const walk = node => {
        for (const c of node.courses || []) {
          if (!c.code || courses.has(c.code)) continue;
          const m = COURSE_URL_RE.exec(c.url || '');
          courses.set(c.code, [c.title || null, c.credits ?? null, m ? `${m[1]}:${m[2]}` : null]);
        }
        (node.children || []).forEach(walk);
      };
      (JSON.parse(readFileSync(path, 'utf-8')).requirements || []).forEach(walk);
    }
  }
  return {
    _meta: { note: 'Auto-generated by test/generate-course-index.js from programs/<year>/**/program.json. Re-run when those change.', years },
    courses: Object.fromEntries([...courses].sort(([a], [b]) => a.localeCompare(b))),
  };
}
