/**
 * Saved catalog HTML → plain catalog data, shared by generate-catalog-json.js
 * (which writes it) and test-catalog-snapshot.js (which checks the committed
 * output still matches the saved HTML).
 */

import { JSDOM } from 'jsdom';
import { parseCoreProgram } from '../src/core.js';

// Update savedAt when re-saving a catalog page from the browser.
export const CATALOG_INFO = {
  '24': { catalogYear: '2025-26', navoid: '780', savedAt: '2026-10-15' },
  '25': { catalogYear: '2026-27', navoid: '803', savedAt: '2026-10-15' },
};

export function catalogPageUrl(catoid) {
  return `https://catalog.calvin.edu/content.php?catoid=${catoid}&navoid=${CATALOG_INFO[catoid].navoid}`;
}

// Strip DOM-only fields, keep everything analyze() and the app need.
export function buildCatalogJson(html, catoid) {
  const doc = new JSDOM(html).window.document;
  const categories = parseCoreProgram(doc).map(cat => {
    const base = {
      type: cat.type,
      section: cat.section,
      name: cat.name,
      instructions: cat.instructions,
      coreIndex: cat.coreIndex,
      slug: cat.slug,
      coreId: cat.coreId,
    };
    if (cat.type === 'section-header') return cat.kuAggregate ? { ...base, kuAggregate: cat.kuAggregate } : base;
    return {
      ...base,
      reqType: cat.reqType,
      minHours: cat.minHours,
      maxHours: cat.maxHours,
      maxPerDiscipline: cat.maxPerDiscipline,
      ...(cat.alternatives && { alternatives: cat.alternatives }),
      courses: (cat.courses || []).map(c => ({
        code: c.code,
        title: c.title,
        subDiscipline: c.subDiscipline,
        coid: c.coid,
        ...(c.connectorBefore && { connectorBefore: c.connectorBefore }),
      })),
    };
  });
  const info = CATALOG_INFO[catoid] || {};
  return {
    _meta: {
      catoid,
      catalogYear: info.catalogYear || null,
      navoid: info.navoid || null,
      sourceUrl: info.navoid ? catalogPageUrl(catoid) : null,
      savedAt: info.savedAt || null,
      generatedFrom: `catalog-${catoid}.html`,
      note: 'Auto-generated by test/generate-catalog-json.js. Re-run when catalog changes.',
    },
    categories,
  };
}

// catalogs: [{ _meta, categories }], newest first: its sub-discipline wins.
export function buildUnion(catalogs) {
  const union = {};
  for (const data of catalogs) {
    for (const cat of data.categories) {
      if (!cat.name || !cat.courses?.length) continue;
      union[cat.name] ??= {};
      for (const c of cat.courses) {
        if (!(c.code in union[cat.name])) union[cat.name][c.code] = c.subDiscipline || null;
      }
    }
  }
  for (const name of Object.keys(union)) {
    union[name] = Object.fromEntries(Object.entries(union[name]).sort(([a], [b]) => a.localeCompare(b)));
  }
  const sources = catalogs.map(d => `${d._meta.catoid} (${d._meta.catalogYear})`);
  return `// Auto-generated by test/generate-catalog-json.js. Do not edit.
// Union of core course lists from catalogs ${sources.join(', ')}.
// { [category name]: { [course code]: sub-discipline or null } }
export const KNOWN_COURSE_CATEGORIES = ${JSON.stringify(union, null, 2)};
`;
}
