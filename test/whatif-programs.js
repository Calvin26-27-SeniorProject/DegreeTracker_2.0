// The majors and minors the What if tab offers, from the generated
// programs/<year>/**/program.json pages, cut down to what an estimate needs:
// each requirement block's heading and the courses it lists. Titles, hours, and
// links come from programs/course-index.json.
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
export const PROGRAMS_DIR = join(ROOT, 'programs');
export const WHATIF_PATH = join(PROGRAMS_DIR, 'whatif-programs.json');
const TYPES = ['Major', 'Minor'];
const POID_RE = /[?&]poid=(\d+)/;

function programFiles(dir) {
  const found = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...programFiles(path));
    else if (entry.name === 'program.json') found.push(path);
  }
  return found.sort();
}

// { _meta, catalogs: { [catoid]: { catalogYear, programs: [{ name, type, poid,
//   totalHours, blocks: [[heading, depth, [codes], section]] }] } } }, programs
// by name. A block is a requirement node with courses; depth 0 is a top-level
// section ("Program Requirements"), deeper ones its "Take One from the
// Following" etc.; section is the heading of the top-level node it sits in.
export function buildWhatIfPrograms(dir = PROGRAMS_DIR) {
  const catalogs = {};
  const years = readdirSync(dir).filter(d => /^\d{4}$/.test(d)).sort().reverse();
  for (const year of years) {
    for (const path of programFiles(join(dir, year))) {
      const p = JSON.parse(readFileSync(path, 'utf-8'));
      if (!TYPES.includes(p.type) || !p.catalog?.catoid) continue;
      const blocks = [];
      const walk = (node, depth, section) => {
        const codes = (node.courses || []).map(c => c.code).filter(Boolean);
        if (codes.length) blocks.push([node.name || '', depth, codes, section]);
        (node.children || []).forEach(child => walk(child, depth + 1, section));
      };
      (p.requirements || []).forEach(r => walk(r, 0, r.name || ''));
      if (!blocks.length) continue;
      const cat = catalogs[p.catalog.catoid] ||= { catalogYear: p.catalog.year, programs: [] };
      cat.programs.push({ name: p.name, type: p.type, poid: POID_RE.exec(p.sourceUrl || '')?.[1] ?? null, totalHours: p.totalHours ?? null, blocks });
    }
  }
  for (const cat of Object.values(catalogs)) cat.programs.sort((a, b) => a.name.localeCompare(b.name));
  return {
    _meta: { note: 'Auto-generated by test/generate-whatif-programs.js from programs/<year>/**/program.json (majors and minors). Re-run when those change.' },
    catalogs,
  };
}
